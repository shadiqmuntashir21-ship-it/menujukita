export async function logOrderEmail(db:any,orderId:string,kind:string,recipient:string,fn:()=>Promise<string>){
 try{
  const providerId=await fn();
  await db`INSERT INTO email_events(order_id,kind,recipient,status,provider_id) VALUES(${orderId},${kind},${recipient},'sent',${providerId||null})`;
  await addOrderActivity(db,orderId,"email_sent",{kind,recipient});
  return true;
 }catch(e:any){
  await db`INSERT INTO email_events(order_id,kind,recipient,status,error) VALUES(${orderId},${kind},${recipient},'failed',${String(e?.message||e).slice(0,500)})`;
  await addOrderActivity(db,orderId,"email_failed",{kind,recipient,error:String(e?.message||e).slice(0,180)});
  return false;
 }
}
const money=(n:any)=>new Intl.NumberFormat("id-ID",{style:"currency",currency:"IDR",maximumFractionDigits:0}).format(Number(n||0));
const htmlEntities:Record<string,string>={"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;"};
const safe=(value:any)=>String(value??"").replace(/[&<>"]/g,c=>htmlEntities[c]||c);

